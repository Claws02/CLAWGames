// The course checker: every layer, every course, and the toy-box hub.
//   node src/games/parkour/tools/check.mjs                 # all courses + hub. Must be 0 errors, 0 warnings.
//   node src/games/parkour/tools/check.mjs c2 --verbose    # one course, with route details
//   node src/games/parkour/tools/check.mjs --write-tapes   # after a clean run: regenerate levels/tapes.js
import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import { COURSES, HUB } from '../levels/index.js';
import { lintCourse, lintHub } from '../core/Lint.js';

const args = process.argv.slice(2);
const only = args.find(a => !a.startsWith('--'));
const verbose = args.includes('--verbose'), write = args.includes('--write-tapes');
const t0 = Date.now();
let errors = 0, warnings = 0;
const tapes = {};

for (const c of COURSES) {
    if (only && c.id !== only) continue;
    const s = Date.now();
    const r = lintCourse(c);
    errors += r.errors.length; warnings += r.warnings.length;
    const mark = r.errors.length ? '✗' : r.warnings.length ? '!' : '✓';
    const i = r.info;
    console.log(`${mark} ${c.id.padEnd(4)} ${c.name.padEnd(16)} par ${String(c.par?.seconds).padStart(3)}s · route ${i.goalSeconds ?? '—'}s · ★★★ route ${i.allSeconds ?? '—'}s · ${((Date.now() - s) / 1000).toFixed(1)}s`);
    if (verbose) console.log(`       states: goal ${i.goalStates}, all coins ${i.allStates}`);
    for (const e of r.errors) console.log(`    ERROR ${e}`);
    for (const e of r.warnings) console.log(`    warn  ${e}`);
    if (r.tapes) tapes[c.id] = r.tapes;
}
if (!only) {
    const h = lintHub(HUB, COURSES);
    errors += h.errors.length; warnings += h.warnings.length;
    console.log(`${h.errors.length ? '✗' : '✓'} hub  ${HUB.name}: ${HUB.devices.filter(d => d.type === 'portal').length} doors`);
    for (const e of h.errors) console.log(`    ERROR ${e}`);
    for (const e of h.warnings) console.log(`    warn  ${e}`);
}
console.log(`\n${COURSES.length} courses · ${errors} errors · ${warnings} warnings · ${((Date.now() - t0) / 1000).toFixed(1)}s`);

if (write) {
    if (errors || only) { console.log('Not writing tapes: needs a clean run over every course.'); process.exit(1); }
    const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'levels', 'tapes.js');
    writeFileSync(out, '// GENERATED by tools/check.mjs --write-tapes. Never hand-edit.\n' +
        '// Each course: goal = a route to the toy chest, all = a route through all 3 coins to it.\n' +
        `export const TAPES = ${JSON.stringify(tapes)};\n`);
    console.log(`wrote ${out}`);
}
process.exit(errors ? 1 : 0);
