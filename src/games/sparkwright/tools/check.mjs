// usage: node tools/check.mjs [levelId ...] [--write-tapes] [--json]
// Runs all six lint layers over every level in levels/index.js (or the ids given).
// Exit code 1 on any error or warning — a level ships clean.
import { LEVELS, HUB } from '../levels/index.js';
import { lintAll } from '../core/Lint.js';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const only = args.filter(a => !a.startsWith('--'));
const ALL = [HUB, ...LEVELS];
const pick = only.length ? ALL.filter(l => only.includes(l.id)) : ALL;
const t0 = Date.now();
const { results, cross } = lintAll(pick, { campaign: LEVELS, campaignIds: LEVELS.map(l => l.id) });
let e = 0, w = 0;
const LAYER = ['', 'data', 'layout', 'puzzle', 'reach', 'ghost', 'progress'];
for (const r of results) {
    const s = r.stats;
    const head = `${r.id.padEnd(5)} ${(pick.find(l => l.id === r.id)?.name || '').padEnd(22)}`;
    const meta = s.doors ? `hub · ${s.doors} doors · ${s.states} states` : s.frames ? `route ${s.seconds}s · ${s.states} states${s.assignments ? ` · ${s.solvable}/${s.assignments} builds work, ${s.threeStar} earn ★★★ (${s.classes} groups)` : ''}` : '';
    console.log(`${r.problems.length ? '✗' : '✓'} ${head} ${meta}`);
    for (const p of r.problems) {
        console.log(`    ${p.level === 'error' ? '✗' : '·'} [${LAYER[p.layer]}] ${p.what}`);
        p.level === 'error' ? e++ : w++;
    }
    if (args.includes('--verbose') && s.works) console.log('      ★★★ builds:', s.works.join('   ·   '));
}
for (const p of cross) { console.log(`  ✗ [${LAYER[p.layer]}] ${p.what}`); p.level === 'error' ? e++ : w++; }
console.log(`\n${results.length} levels · ${e} errors · ${w} warnings · ${((Date.now() - t0) / 1000).toFixed(1)}s`);

if (args.includes('--write-tapes')) {
    if (e || w || only.length) { console.log('tapes NOT written (needs a clean full run)'); process.exit(1); }
    const out = {};
    for (const r of results) if (r.tape) out[r.id] = r.tape;
    const file = fileURLToPath(new URL('../levels/tapes.js', import.meta.url));
    writeFileSync(file, '// GENERATED by tools/check.mjs --write-tapes. Do not edit.\n// Solver input tapes: the arcade bot and qa probe replay these.\n// [[bits, frames, act?]] bits: l=1 r=2 u=4 d=8 j=16\nexport const TAPES = ' + JSON.stringify(out) + ';\n');
    console.log('wrote levels/tapes.js');
}
process.exit(e || w ? 1 : 0);
